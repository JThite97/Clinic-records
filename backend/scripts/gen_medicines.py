TARGET = 500


def build() -> list[dict]:
    out = []
    for generic, cat, forms, dose, freq, dur, instr in LIB:
        for form, strength in forms:
            d = dose
            if form in (S, SUS) and dose.endswith("tab"):
                d = "5 ml"
            elif form == C and dose == "1 tab":
                d = "1 cap"
            elif form in (CRM, OINT, GEL, LOT) and not dose.startswith("Apply"):
                d = "Apply"
            elif form == DROP and dose.endswith("tab"):
                d = "As directed"
            elif form == INJ and dose.endswith(("tab", "cap")):
                d = "1 amp"
            out.append({
                "name": f"{generic} {strength}".strip(),
                "generic_name": generic,
                "form": form,
                "strength": strength,
                "category": cat,
                "default_dose": d,
                "default_frequency": freq,
                "default_duration": dur,
                "default_instructions": instr,
            })
    seen, uniq = set(), []
    for m in out:
        k = (m["name"].lower(), m["form"].lower())
        if k not in seen:
            seen.add(k)
            uniq.append(m)
    return uniq


